# -*- coding: utf-8 -*-
"""Rigenera MANUALE.md e MANUALE.en.md unendo le sezioni della Guida.

La Guida (file .md in questa cartella) e' la fonte unica: i due MANUALE sono
solo una versione "tutto in un file" per chi legge il repository senza
installare il plugin. Dopo aver modificato una sezione, eseguire:

    python guida/_genera_manuale.py

L'ordine delle sezioni e' quello di ui/guida_dialog.py (SECTIONS).
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
G = ROOT / "guida"

# Stesso ordine di SECTIONS in ui/guida_dialog.py
ORDER = [
    "00_introduzione", "01_fisica_di_base", "02_interfaccia",
    "13_verifica_condotte", "03_prepara_rete", "04_parametri_simulazione",
    "05_avvio_simulazione", "08_layer_output", "06_risultati_nodi",
    "07_risultati_condotte", "12_tutorial", "10_risoluzione_problemi",
    "09_riferimenti_tecnici", "11_glossario",
]

HEAD = {
    "it": ("# Manuale — GasNetSim 4Qgis\n\n"
           "Plugin QGIS per la simulazione idraulica in regime stazionario di reti di\n"
           "trasporto gas, basato sul motore di calcolo GasNetSim.\n\n"
           "> Questo file è generato unendo le sezioni della Guida integrata nel plugin\n"
           "> (cartella `guida/`, visibile dal pulsante **Guida**). Non modificarlo a\n"
           "> mano: le modifiche vanno fatte nei file della cartella `guida/`, poi si\n"
           "> rilancia `python guida/_genera_manuale.py`.\n\n"
           "## Indice\n\n"),
    "en": ("# Manual — GasNetSim 4Qgis\n\n"
           "QGIS plugin for steady-state hydraulic simulation of gas transmission\n"
           "networks, built on the GasNetSim calculation engine.\n\n"
           "> This file is generated by concatenating the sections of the Guide built\n"
           "> into the plugin (folder `guida/`, reachable from the **Guide** button).\n"
           "> Do not edit it by hand: edit the files in `guida/`, then re-run\n"
           "> `python guida/_genera_manuale.py`.\n\n"
           "## Contents\n\n"),
}


def _anchor(title: str) -> str:
    a = title.lower()
    for ch in "—·,.:()/'\"’":
        a = a.replace(ch, "")
    a = a.replace(" ", "-")
    while "--" in a:
        a = a.replace("--", "-")
    return a.strip("-")


def build(lang: str, out_name: str) -> None:
    parts, toc = [], []
    for i, sid in enumerate(ORDER, 1):
        path = G / f"{sid}.{lang}.md"
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8").strip()
        title = text.splitlines()[0].lstrip("# ").strip()
        toc.append(f"{i}. [{title}](#{_anchor(title)})")
        # Declassa i titoli di un livello: l'H1 del manuale resta unico.
        body = "\n".join(("#" + ln) if ln.startswith("#") else ln
                         for ln in text.splitlines())
        parts.append(body)
    (ROOT / out_name).write_text(
        HEAD[lang] + "\n".join(toc) + "\n\n---\n\n" + "\n\n---\n\n".join(parts) + "\n",
        encoding="utf-8")
    print(f"{out_name}: {len(parts)} sezioni")


if __name__ == "__main__":
    build("it", "MANUALE.md")
    build("en", "MANUALE.en.md")
